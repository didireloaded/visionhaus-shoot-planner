import assert from 'node:assert/strict';
import {initial,change,total,priceLines,restore,narrative,reviewItems} from '../dist/domain.mjs';
let s=change(initial(),'service','Video');
assert.equal(total(s),0);
s=change(s,'project','Podcast');
const base=total(s);
s=change(s,'people',4);assert.equal(total(s)-base,500);
s=change(s,'framing','Full coverage');assert.equal(s.cameras,3);
assert.equal(total(s)-base,1700);
s=change(s,'extras',['clips']);assert.equal(total(s)-base,2900);
s=change(s,'extras',[]);assert.equal(total(s)-base,1700);
s=change(s,'episodes',2);assert.equal(total(s)-base,3200);
assert.match(narrative(s),/4-person podcast.*3 camera angles.*2 edited episodes/);
s=change(s,'location','Swakopmund');assert.ok(reviewItems(s).includes('Travel & accommodation'));
s=change(s,'service','Photo');assert.equal(s.project,'');assert.equal(s.cameras,1);assert.deepEqual(s.extras,[]);assert.equal(s.episodes,1);
s=change(s,'project','Portraits');assert.ok(!priceLines(s).some(x=>/camera/.test(x.label)));
s=change(s,'service','Editing');s=change(s,'project','Podcast edit');assert.ok(!priceLines(s).some(x=>/camera|location|Audio/.test(x.label)));assert.ok(!narrative(s).includes('hours'));
assert.equal(restore({service:'Video',project:'Fake',people:999}).project,'');assert.equal(restore({service:'Video',people:999}).people,2);
console.log('Pricing deltas, dependencies, switching, review flags and draft validation passed.');
