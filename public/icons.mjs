export function icon(name) {
  if (!Object.hasOwn(iconPaths, name)) throw new Error('Unknown icon: ' + name);
  return (
    '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round" class="lucide lucide-' +
    name +
    '" aria-hidden="true">' +
    iconPaths[name]
      .map(
        ([tag, attrs]) =>
          '<' +
          tag +
          ' ' +
          Object.entries(attrs)
            .map(([key, value]) => key + '="' + value + '"')
            .join(' ') +
          '/>',
      )
      .join('') +
    '</svg>'
  );
}
